                            Surface(
                                color = if (speaker.contains("Host", ignoreCase = true) || speaker.contains("Narrator", ignoreCase = true)) {
                                    GeminiCyanAccent.copy(alpha = 0.2f)
                                } else {
                                    GeminiSparklePurple.copy(alpha = 0.2f)
                                },
                                shape = RoundedCornerShape(4.dp)
                            ) {
                                Text(
                                    text = speaker,
                                    fontSize = 10.sp,
                                    fontWeight = FontWeight.Bold,
                                    color = if (speaker.contains("Host", ignoreCase = true) || speaker.contains("Narrator", ignoreCase = true)) GeminiCyanAccent else GeminiSparklePurple,
                                    modifier = Modifier.padding(horizontal = 4.dp, vertical = 1.dp)
