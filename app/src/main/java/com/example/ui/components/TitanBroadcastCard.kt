                                    )
                                    Text(
                                        text = "S${scene.sceneNumber}",
                                        fontSize = 10.sp,
                                        fontWeight = FontWeight.Bold,
                                        color = Color.White,
                                        modifier = Modifier
                                            .align(Alignment.BottomEnd)
                                            .padding(3.dp)
                                    )
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}

/**
 * Creates 4 cinematic scenes for video reel generation based on script prompt
 */
private suspend fun createCinematicScenes(context: Context, script: String): List<BroadcastScene> = withContext(Dispatchers.IO) {
    val topic = script.lines().firstOrNull { it.isNotBlank() }?.take(40)?.replace(Regex("[^a-zA-Z0-9 ]"), "") ?: "cinematic documentary story"

    val prompts = listOf(
        Pair("Act I: Ambiance & Setting", "cinematic opening wide establishing shot of $topic atmospheric dramatic volumetric lighting 8k photorealistic"),
        Pair("Act II: Character In Action", "medium close up shot dramatic character expression dynamic movement cinematic film still 8k"),
        Pair("Act III: The Turning Point", "epic climax visual spectacle high tension vibrant colors cinematic color grading 8k unreal engine 5"),
        Pair("Act IV: Cinematic Resolution", "cinematic closing shot warm golden hour lighting emotional depth ultra detailed masterpiece 8k")
    )

    prompts.mapIndexed { index, (title, visualPrompt) ->
        async {
            val imageUrl = TitanMediaGateway.generateImagen3Artwork(context, visualPrompt)
            BroadcastScene(
                sceneNumber = index + 1,
                title = title,
                description = "Synthesized scene ${index + 1} motion reel frame with Google Imagen 3 & Veo 2.",
                visualPrompt = visualPrompt,
                imageUrl = imageUrl
            )
        }
    }.awaitAll()
}
