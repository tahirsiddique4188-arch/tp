                        Text(
                            text = "Export & Share Broadcast",
                            fontSize = 11.sp,
                            fontWeight = FontWeight.SemiBold,
                            color = GeminiTextSecondary
                        )

                        Row(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                            // WhatsApp Share
                            FilledTonalButton(
                                onClick = {
                                    val shareIntent = Intent(Intent.ACTION_SEND).apply {
                                        type = "text/plain"
                                        putExtra(Intent.EXTRA_SUBJECT, "Titan Studio Broadcast Script")
                                        putExtra(
                                            Intent.EXTRA_TEXT,
                                            "🎙️ *Titan Studio Multi-Speaker Audio Broadcast*\n\n$scriptContent\n\n_Generated via Titan IDE Omni by Developer Tahir (@Tahirsiddik)_"
                                        )
                                        setPackage("com.whatsapp")
                                    }
                                    try {
                                        context.startActivity(shareIntent)
                                    } catch (e: Exception) {
                                        // Fallback to normal share chooser
                                        val genericIntent = Intent(Intent.ACTION_SEND).apply {
