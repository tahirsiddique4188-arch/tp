                            isGeneratingVideo = true
                            coroutineScope.launch {
                                val scenes = createCinematicScenes(context, scriptContent)
                                generatedScenes = scenes
                                isGeneratingVideo = false
                                selectedSceneIndex = 0
                                Toast.makeText(context, "🎬 4-Scene cinematic motion reel generated!", Toast.LENGTH_SHORT).show()
                            }
