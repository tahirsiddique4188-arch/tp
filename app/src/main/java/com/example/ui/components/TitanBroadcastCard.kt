@Composable
fun TitanBroadcastCard(
    scriptContent: String,
    onSpeakClick: (String) -> Unit,
    modifier: Modifier = Modifier
) {
    val context = LocalContext.current
    val coroutineScope = rememberCoroutineScope()

    var isGeneratingAudio by remember { mutableStateOf(false) }
    var audioGenerated by remember { mutableStateOf(false) }

    var isGeneratingVideo by remember { mutableStateOf(false) }
    var generatedScenes by remember { mutableStateOf<List<BroadcastScene>>(emptyList()) }
    var selectedSceneIndex by remember { mutableIntStateOf(0) }

    // Parse lines to detect speaker cues
    val scriptLines = remember(scriptContent) {
        scriptContent.lines().filter { it.isNotBlank() }
    }

    Card(
        shape = RoundedCornerShape(16.dp),
        colors = CardDefaults.cardColors(containerColor = GeminiSurface),
        border = BorderStroke(1.dp, GeminiThinkingBorder),
        modifier = modifier
            .fillMaxWidth()
            .padding(vertical = 6.dp)
    ) {
        Column(modifier = Modifier.padding(14.dp)) {
            // Header Banner
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Box(
                        modifier = Modifier
                            .size(28.dp)
                            .clip(CircleShape)
                            .background(
                                Brush.linearGradient(
                                    listOf(GeminiSparklePurple, GeminiCyanAccent)
                                )
                            ),
                        contentAlignment = Alignment.Center
                    ) {
                        Icon(
                            imageVector = Icons.Default.Podcasts,
                            contentDescription = null,
                            tint = Color.White,
                            modifier = Modifier.size(16.dp)
                        )
                    }
                    Spacer(modifier = Modifier.width(8.dp))
                    Column {
                        Text(
                            text = "Titan Broadcast Script",
                            fontSize = 13.5.sp,
                            fontWeight = FontWeight.Bold,
                            color = GeminiTextPrimary
                        )
                        Text(
                            text = "Multi-Speaker Production Ready",
                            fontSize = 10.sp,
                            color = GeminiCyanAccent
                        )
                    }
                }

                Surface(
                    color = GeminiCyanAccent.copy(alpha = 0.15f),
                    shape = RoundedCornerShape(8.dp),
                    border = BorderStroke(0.5.dp, GeminiCyanAccent.copy(alpha = 0.4f))
                ) {
                    Text(
                        text = "STUDIO V2",
                        fontSize = 9.sp,
                        fontWeight = FontWeight.Bold,
                        color = GeminiCyanAccent,
                        modifier = Modifier.padding(horizontal = 6.dp, vertical = 2.dp)
                    )
                }
            }

            Spacer(modifier = Modifier.height(10.dp))

            // Script Preview with speaker highlights
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .background(GeminiDarkObsidian, RoundedCornerShape(10.dp))
                    .padding(10.dp)
            ) {
                scriptLines.take(6).forEach { line ->
                    val isSpeakerCue = line.contains(":") && (line.startsWith("**") || line.startsWith("["))
                    Row(
                        modifier = Modifier.padding(vertical = 2.dp),
                        verticalAlignment = Alignment.Top
                    ) {
                        if (isSpeakerCue) {
                            val speaker = line.substringBefore(":").replace("*", "").replace("[", "").replace("]", "").trim()
