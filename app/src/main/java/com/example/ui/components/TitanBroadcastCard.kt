                        Icon(
                            imageVector = if (audioGenerated) Icons.Default.Check else Icons.Default.Mic,
                            contentDescription = null,
                            tint = if (audioGenerated) Color.White else GeminiDarkObsidian,
                            modifier = Modifier.size(16.dp)
